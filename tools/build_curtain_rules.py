"""Rebuild supabase/functions/ready-curtains/rules.ts from rules.json (the single source of truth for how the agent
draws curtains; the CurtainsImages skill reads rules.json directly). Run after every edit of rules.json, then redeploy."""
import json
from pathlib import Path

d = Path(__file__).resolve().parent.parent / "supabase" / "functions" / "ready-curtains"
rules = json.loads((d / "rules.json").read_text(encoding="utf-8"))
# only what the function needs: it edits golden pictures, so construction references, scene texts and demo data stay out
KEEP = ("version", "model", "opacity", "tieback", "window_shots", "view_text", "sheer_wall_text", "sheer_wall_shots", "golden_prompt",
        "house_rules", "modify_prompt", "feedback_prompt", "qc")
rules = {**{k: rules[k] for k in KEEP},
         "styles": {k: {"label": v["label"]} for k, v in rules["styles"].items()},
         "shots": rules["shots"]}
(d / "rules.ts").write_text(
    "// GENERATED by tools/build_curtain_rules.py from rules.json - do not edit by hand.\n"
    "// deno-lint-ignore-file no-explicit-any\n"
    "const RULES: any = " + json.dumps(rules, indent=2, ensure_ascii=False) + ";\nexport default RULES;\n",
    encoding="utf-8")
print("rules.ts written")
